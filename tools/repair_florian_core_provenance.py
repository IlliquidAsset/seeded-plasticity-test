#!/usr/bin/env python3
"""One-off, metadata-only provenance repair of results_florian_core (no science rerun).

Nora's review of 2c7cd6b: the recorded ``command`` omitted the required
``--gate-commit`` and the run's ``--g0``, so it was not executable.  The actual
invocation is recovered verbatim from the Hermes durable process record
``~/.hermes/profiles/ethan/logs/process-results/proc_4affc9917d7f.json``
(exit_code 0, cwd = repo root, started_at 1790820863.97).  Nothing is inferred.

Only top-level provenance keys change (command, argv, argv_normalized,
provenance_repair).  ``runs`` and ``groups`` are asserted byte-identical before
and after; the report is regenerated by the same ``_report`` function.
"""

import hashlib
import json
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import run_florian_core as rfc  # noqa: E402

RECORD = Path.home() / ".hermes/profiles/ethan/logs/process-results/proc_4affc9917d7f.json"


def _h(obj):
    return hashlib.sha256(json.dumps(obj, sort_keys=True).encode()).hexdigest()


def main():
    rec = json.loads(RECORD.read_text())
    assert rec["exit_code"] == 0 and rec["completion_reason"] == "exited", rec
    assert Path(rec["cwd"]).resolve() == ROOT, rec["cwd"]
    shell_cmd = rec["command"]
    # Strip only the shell redirection (not part of the process argv).
    tokens = shlex.split(shell_cmd)
    redir = tokens.index(">")
    assert tokens[redir + 1:] == [str(Path.home() / ".hermes/profiles/ethan/cache/scratch/florian_core_run.log"), "2>&1"], tokens
    argv = tokens[:redir]
    assert argv[0] == "~/.hermes/hermes-agent/venv/bin/python3.11" and argv[1] == "run_florian_core.py", argv
    argv[0] = str(Path(argv[0]).expanduser())  # the shell expanded ~ before exec

    ap = rfc.build_parser()
    args = ap.parse_args(argv[2:])

    path = rfc.SUMMARY
    raw = path.read_text()
    payload = json.loads(raw)
    assert json.dumps(payload, indent=2, sort_keys=True) + "\n" == raw, "summary.json does not re-serialize byte-identically"
    before = (_h(payload["runs"]), _h(payload["groups"]), len(payload["runs"]))
    assert args.gate_commit == payload["gate_commit"] and args.g0 == payload["G0"]
    assert (args.seeds, args.epochs) == (20, 200) and len(payload["runs"]) == 160

    old_cmd = payload["command"]
    payload["command"] = shlex.join(argv)
    payload["argv"] = argv
    payload["argv_normalized"] = [argv[0], "run_florian_core.py", *rfc.argv_from_args(args, ap)]
    payload["provenance_repair"] = {
        "note": "metadata-only repair after Nora review of 2c7cd6b; no science rerun; runs/groups unchanged. "
        "Exact argv recovered verbatim from Hermes process record proc_4affc9917d7f (exit 0).",
        "previous_command": old_cmd,
        "source_record": "~/.hermes/profiles/ethan/logs/process-results/proc_4affc9917d7f.json",
        "source_shell_command": shell_cmd,
        "repaired_by": "tools/repair_florian_core_provenance.py",
    }
    assert (_h(payload["runs"]), _h(payload["groups"]), len(payload["runs"])) == before
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    rfc._report(payload)
    print(json.dumps({"runs_sha": before[0], "groups_sha": before[1], "command": payload["command"]}, indent=2))


if __name__ == "__main__":
    main()
